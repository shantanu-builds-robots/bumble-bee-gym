"""Render a Course into a Gazebo Classic world (SDF) and a MuJoCo scene (MJCF) with the Bumble Bee drone."""

from __future__ import annotations

import struct
from pathlib import Path
from xml.sax.saxutils import quoteattr

import numpy as np

from . import params as params_mod
from .course import PAD_SIZE, PARCEL_MASS, PARCEL_SIZE, Course

# Physics shared by both simulators (Gazebo's delivery_area.world uses the same values).
TIMESTEP = 0.001
GRAVITY = 9.8

GATE_RGBA = "0.95 0.45 0.05 1"
BUILDING_RGBA = "0.55 0.57 0.6 1"


def _f(v) -> str:
    return " ".join(f"{x:.6g}" for x in np.ravel(v))


def _yaw_quat(yaw_deg: float) -> np.ndarray:
    a = np.radians(yaw_deg) / 2
    return np.array([np.cos(a), 0.0, 0.0, np.sin(a)])


def _rot_z(yaw_deg: float) -> np.ndarray:
    a = np.radians(yaw_deg)
    return np.array([[np.cos(a), -np.sin(a), 0], [np.sin(a), np.cos(a), 0], [0, 0, 1]])


def _mat_quat(r: np.ndarray) -> np.ndarray:
    """Rotation matrix to (w, x, y, z) quaternion."""
    w = np.sqrt(max(0.0, 1 + r[0, 0] + r[1, 1] + r[2, 2])) / 2
    x = np.copysign(np.sqrt(max(0.0, 1 + r[0, 0] - r[1, 1] - r[2, 2])) / 2, r[2, 1] - r[1, 2])
    y = np.copysign(np.sqrt(max(0.0, 1 - r[0, 0] + r[1, 1] - r[2, 2])) / 2, r[0, 2] - r[2, 0])
    z = np.copysign(np.sqrt(max(0.0, 1 - r[0, 0] - r[1, 1] + r[2, 2])) / 2, r[1, 0] - r[0, 1])
    return np.array([w, x, y, z])


def stl_bounds(path: Path, pose: np.ndarray = np.eye(4)) -> tuple[np.ndarray, np.ndarray]:
    """Axis-aligned bounds of a binary STL after applying a 4x4 pose."""
    data = path.read_bytes()
    n = struct.unpack("<I", data[80:84])[0]
    tri = np.frombuffer(data[84:84 + 50 * n], dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]))
    pts = tri["v"].reshape(-1, 3).astype(float)
    pts = pts @ pose[:3, :3].T + pose[:3, 3]
    return pts.min(0), pts.max(0)


# ----------------------------------------------------------------------------------------------- Gazebo

def to_sdf(course: Course) -> str:
    """Gazebo Classic world for the course. The drone is spawned separately by bumble-bee's launch file."""
    out = [f"""<?xml version="1.0"?>
<!-- Generated by bumble-bee-gym from courses/{course.name}.yaml. Do not edit by hand. -->
<sdf version="1.6">
  <world name="default">
    <include><uri>model://sun</uri></include>
    <include><uri>model://ground_plane</uri></include>
    <gravity>0 0 -{GRAVITY}</gravity>
    <physics type="ode">
      <max_step_size>{TIMESTEP}</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>{int(round(1 / TIMESTEP))}</real_time_update_rate>
    </physics>
    <scene>
      <grid>false</grid>
      <origin_visual>false</origin_visual>
      <ambient>0.4 0.4 0.4 1</ambient>
      <background>0.7 0.7 0.7 1</background>
      <shadows>1</shadows>
    </scene>"""]
    for i, p in enumerate(course.pads):
        out.append(f"""    <include>
      <uri>model://landing_pad</uri>
      <name>landing_pad_{i}</name>
      <static>true</static>
      <pose>{_f(p)} 0 0 0</pose>
    </include>""")
    for model, xyz in course.parcels:
        out.append(f"""    <include>
      <uri>model://{model}</uri>
      <name>{model}</name>
      <pose>{_f(xyz + [0, 0, PARCEL_SIZE / 2])} 0 0 0</pose>
    </include>""")
    for i, b in enumerate(course.buildings):
        sx, sy, h = b.size
        out.append(f"""    <model name="building_{i}">
      <static>true</static>
      <pose>{_f([b.xyz[0], b.xyz[1], h / 2])} 0 0 {np.radians(b.yaw):.6g}</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{_f(b.size)}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{_f(b.size)}</size></box></geometry>
          <material><ambient>{BUILDING_RGBA}</ambient><diffuse>{BUILDING_RGBA}</diffuse></material></visual>
      </link>
    </model>""")
    for i, g in enumerate(course.gates):
        bars = []
        for j, (c, half) in enumerate(g.bars()):
            size = _f(2 * half)
            bars.append(f"""        <collision name="bar_{j}"><pose>{_f(c)} 0 0 0</pose><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="bar_{j}"><pose>{_f(c)} 0 0 0</pose><geometry><box><size>{size}</size></box></geometry>
          <material><ambient>{GATE_RGBA}</ambient><diffuse>{GATE_RGBA}</diffuse></material></visual>""")
        out.append(f"""    <model name="gate_{i}">
      <static>true</static>
      <pose>{_f(g.xyz)} 0 0 {np.radians(g.yaw):.6g}</pose>
      <link name="link">
{chr(10).join(bars)}
      </link>
    </model>""")
    s = course.spawn_xyz
    out.append(f"""    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>{_f([s[0] - 4, s[1] - 4, s[2] + 3])} 0 0.45 0.785</pose>
        <view_controller>orbit</view_controller>
      </camera>
    </gui>
  </world>
</sdf>
""")
    return "\n".join(out)


# ----------------------------------------------------------------------------------------------- MuJoCo

def drone_mjcf(p: params_mod.DroneParams, pos: np.ndarray, yaw_deg: float) -> tuple[str, str, str]:
    """(assets, body, actuators) MJCF fragments for the drone."""
    assets = [f'    <mesh name="{link}" file={quoteattr(str(p.mesh_dir / f))}/>'
              for link, (f, _) in sorted(p.link_meshes.items())]
    geoms = []
    for link, (_, pose) in sorted(p.link_meshes.items()):
        rgba = "0.949 0.718 0.020 1" if link == "base_link" else "0.05 0.05 0.05 1"
        geoms.append(f'      <geom name="{link}_visual" type="mesh" mesh="{link}" pos="{_f(pose[:3, 3])}" '
                     f'quat="{_f(_mat_quat(pose[:3, :3]))}" rgba="{rgba}" contype="0" conaffinity="0" group="2" mass="0"/>')
    base_file, base_pose = p.link_meshes["base_link"]
    lo, hi = stl_bounds(p.mesh_dir / base_file, base_pose)
    geoms.append(f'      <geom name="body_collision" type="box" pos="{_f((lo + hi) / 2)}" size="{_f((hi - lo) / 2)}" '
                 f'rgba="1 0 0 0.3" group="3" mass="0"/>')
    sites, acts = [], []
    tmax = float(p.thrust(p.max_rotor_speed))
    for r in p.rotors:
        sites.append(f'      <site name="{r.name}" pos="{_f(r.position)}" zaxis="{_f(r.axis)}" size="0.01"/>')
        # Thrust along the rotor axis; the same actuator applies the yaw reaction torque
        # (torque_to_thrust per newton, signed by the rotor's spin direction), as drone_plugin does.
        acts.append(f'    <motor name="{r.name}" site="{r.name}" gear="0 0 1 0 0 {r.spin_sign * p.torque_to_thrust:.6g}" '
                    f'ctrllimited="true" ctrlrange="0 {tmax:.6g}"/>')
    body = f"""    <body name="drone" pos="{_f(pos)}" quat="{_f(_yaw_quat(yaw_deg))}">
      <freejoint name="drone_root"/>
      <inertial pos="{_f(p.com)}" mass="{p.mass:.6g}" fullinertia="{_f([p.inertia[0, 0], p.inertia[1, 1], p.inertia[2, 2], p.inertia[0, 1], p.inertia[0, 2], p.inertia[1, 2]])}"/>
{chr(10).join(geoms)}
{chr(10).join(sites)}
      <site name="imu" pos="{_f(p.com)}" size="0.005"/>
    </body>"""
    return "\n".join(assets), body, "\n".join(acts)


def to_mjcf(course: Course, p: params_mod.DroneParams | None = None) -> str:
    """MuJoCo scene: the course plus the drone at the course's spawn pose."""
    p = p or params_mod.load()
    # Gazebo spawns base_link at spawn_xyz; MuJoCo's body frame is base_link too.
    assets, drone, actuators = drone_mjcf(p, course.spawn_xyz, course.spawn_yaw)
    world = []
    hx, hy, hz = (np.array(PAD_SIZE) / 2)
    for i, pad in enumerate(course.pads):
        world.append(f'    <geom name="landing_pad_{i}" type="box" pos="{_f(pad)}" size="{hx} {hy} {hz}" rgba="0.2 0.55 0.85 1"/>')
    for model, xyz in course.parcels:
        s = PARCEL_SIZE / 2
        i_box = PARCEL_MASS * PARCEL_SIZE ** 2 / 6
        world.append(f"""    <body name="{model}" pos="{_f(xyz + [0, 0, s])}">
      <freejoint/>
      <inertial pos="0 0 0" mass="{PARCEL_MASS}" diaginertia="{i_box:.6g} {i_box:.6g} {i_box:.6g}"/>
      <geom type="box" size="{s} {s} {s}" rgba="0.36 0.25 0.15 1" mass="0"/>
    </body>""")
    for i, b in enumerate(course.buildings):
        world.append(f'    <geom name="building_{i}" type="box" pos="{_f([b.xyz[0], b.xyz[1], b.size[2] / 2])}" '
                     f'size="{_f(b.size / 2)}" quat="{_f(_yaw_quat(b.yaw))}" rgba="{BUILDING_RGBA}"/>')
    for i, g in enumerate(course.gates):
        rot = _rot_z(g.yaw)
        for j, (c, half) in enumerate(g.bars()):
            world.append(f'    <geom name="gate_{i}_bar_{j}" type="box" pos="{_f(g.xyz + rot @ c)}" size="{_f(half)}" '
                         f'quat="{_f(_yaw_quat(g.yaw))}" rgba="{GATE_RGBA}"/>')
        world.append(f'    <site name="gate_{i}" pos="{_f(g.xyz)}" quat="{_f(_yaw_quat(g.yaw))}" '
                     f'size="{_f([0.01, g.opening[0] / 2, g.opening[1] / 2])}" type="box" rgba="0 1 0 0.15" group="4"/>')
    return f"""<!-- Generated by bumble-bee-gym from courses/{course.name}.yaml. Do not edit by hand. -->
<mujoco model="bumble_bee_{course.name}">
  <compiler angle="radian" inertiafromgeom="false" autolimits="true"/>
  <option timestep="{TIMESTEP}" gravity="0 0 -{GRAVITY}" integrator="Euler"/>
  <visual>
    <global offwidth="1920" offheight="1080"/>
    <headlight ambient="0.35 0.35 0.35" diffuse="0.45 0.45 0.45" specular="0 0 0"/>
    <quality shadowsize="8192"/>
    <map zfar="200" haze="0.4"/>
    <rgba haze="0.82 0.88 0.95 1"/>
  </visual>
  <asset>
{assets}
    <texture name="sky" type="skybox" builtin="gradient" rgb1="0.45 0.62 0.85" rgb2="0.82 0.88 0.95" width="512" height="3072"/>
    <texture name="grid" type="2d" builtin="checker" rgb1="0.62 0.62 0.62" rgb2="0.58 0.58 0.58" width="512" height="512"/>
    <material name="grid" texture="grid" texrepeat="1 1" texuniform="true"/>
  </asset>
  <worldbody>
    <light pos="0 0 20" dir="-0.3 0.4 -1" directional="true" diffuse="0.7 0.7 0.7" castshadow="true"/>
    <geom name="ground" type="plane" size="0 0 0.05" material="grid"/>
{chr(10).join(world)}
{drone}
  </worldbody>
  <actuator>
{actuators}
  </actuator>
</mujoco>
"""


def write(course: Course, out_dir: Path) -> tuple[Path, Path]:
    """Write <name>.world and <name>.xml into out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    sdf, mjcf = out_dir / f"{course.name}.world", out_dir / f"{course.name}.xml"
    sdf.write_text(to_sdf(course))
    mjcf.write_text(to_mjcf(course))
    return sdf, mjcf
